import { mkdtemp, mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
await mkdir('.test-artifacts',{recursive:true});
const dir=await mkdtemp(join('.test-artifacts','analysis-'));
for(const sub of ['crawlers','web','data']) await mkdir(join(dir,sub));
for(const path of ['crawlers/diff.ts','crawlers/types.ts','crawlers/base.ts','crawlers/opportunity.ts','crawlers/detail-dates.ts','crawlers/schedule.ts','crawlers/partial-crawl.ts','web/model.js','web/exclusions.js','data/learned-exclusions.json','noise-keywords.txt','package.json']) await copyFile(path,join(dir,path));
const now=new Date(),stamp=now.toISOString(),date=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Seoul'}).format(now);
const p={title:'테스트 박물관 학예 보조 모집',organization:'박물관',regDate:date,deadlineDate:'2099-12-31',url:'https://example.org/1',stableId:'retained-test',verificationStatus:'retained',lastConfirmedAt:'2026-09-27T01:00:00Z',postingType:'job'};
const result={site:{id:'test',name:'테스트 박물관',url:'https://example.org'},postings:[p],crawledAt:stamp,error:'test timeout',observedCount:0,retainedCount:1,lastSuccessfulAt:p.lastConfirmedAt};
await writeFile(join(dir,'crawlers/results.json'),JSON.stringify([result]));
await writeFile(join(dir,'crawlers/results.prev.json'),JSON.stringify([{...result,error:undefined,postings:[{...p,verificationStatus:'current'}]}]));
await writeFile(join(dir,'crawlers/experience-results.json'),'[]');
const state={firstSeen:p.lastConfirmedAt,lastSeen:p.lastConfirmedAt,lastFingerprint:'saved',seenCount:5,lastStatus:'fresh',seenDates:['2026-09-27']};
await writeFile(join(dir,'data/opportunity-state.json'),JSON.stringify({[p.stableId]:state}));
const run=spawnSync(process.execPath,['node_modules/tsx/dist/cli.mjs',join(dir,'crawlers/diff.ts')],{encoding:'utf8',windowsHide:true});
if(run.status!==0) throw new Error(run.stderr||run.stdout);
const json=async path=>JSON.parse(await readFile(join(dir,path),'utf8'));
assert.deepEqual((await json('data/opportunity-state.json'))[p.stableId],state);
assert.deepEqual(await json('crawlers/new-postings.json'),[]);
assert.deepEqual(await json('crawlers/opportunity-events.json'),[]);
assert.deepEqual(await json('data/program-series.json'),{});
const summary=await json('crawlers/notification-summary.json');
assert.equal(summary.totals.current,1); assert.equal(summary.totals.new,0);
assert.equal(summary.urgent.length,0); assert.equal(summary.changes.length,0);
assert.equal(summary.sourceIssues[0].status,'ERROR'); assert.equal(summary.sourceIssues[0].retainedCount,1);
console.log('분석 통합 검증 통과: 보존 자료 신규/긴급/이력 횟수/반복 패턴 오인 없음');
